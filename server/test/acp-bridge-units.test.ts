/* The fact every cancellation in the bridge rests on, pinned at the SDK: a
   request sent with `{cancellationSignal, stopWaitingOnCancel: true}` to a
   peer that never answers rejects the moment the signal aborts, as `-32800`
   carrying the abort reason, and the peer is told `$/cancel_request`. The
   handshake clock, `close()` and the probe's deadline all abort such a
   signal; without this the losing side of their races stayed pending for the
   life of the connection. */
const sent: unknown[] = [];
const silentAgent: acp.Stream = {
  // Nothing ever comes back.
  readable: new ReadableStream<acp.AnyMessage>({ start() {} }),
  writable: new WritableStream<acp.AnyMessage>({ write: (frame) => void sent.push(frame) }),
};
const abortedRequest = await (async () => {
  const rpc = acp.client({ name: "test" }).connect(silentAgent);
  try {
    const giveUp = new AbortController();
    const reason = new Error("the agent did not finish the handshake in time");
    const pending = rpc.agent.request(
      acp.methods.agent.initialize,
      { protocolVersion: acp.PROTOCOL_VERSION, clientCapabilities: {} },
      { cancellationSignal: giveUp.signal, stopWaitingOnCancel: true },
    );
    const outcome = pending.then(
      () => ({ settled: "resolved" as const }),
      (error: unknown) => ({ settled: "rejected" as const, error }),
    );
    // Give the request a tick to be written, then give up on it.
    await new Promise((resolve) => setTimeout(resolve, 20));
    giveUp.abort(reason);
    const settled = await Promise.race([outcome, new Promise<{ settled: "hung" }>((resolve) => setTimeout(() => resolve({ settled: "hung" }), 500))]);
    return { settled, reason };
  } finally {
    rpc.close();
  }
})();

test("an aborted request with stopWaitingOnCancel rejects at once, -32800, with the reason as data", () => {
  assert.equal(abortedRequest.settled.settled, "rejected", "the request stayed pending after its signal aborted");
  const error = (abortedRequest.settled as { error: unknown }).error;
  assert.ok(error instanceof acp.RequestError, "a RequestError");
  assert.equal(error.code, -32800);
  assert.equal(error.data, abortedRequest.reason, "the abort reason rides as data, so the caller knows which clock fired");
  assert.equal(isSessionNotFound(error, "ses_1"), false, "and is never mistaken for a lost session");
});

test("the peer is told the request was cancelled ($/cancel_request names the request's id)", () => {
  const frames = sent as { method?: string; id?: unknown; params?: { requestId?: unknown } }[];
  const request = frames.find((f) => f.method === "initialize");
  const cancel = frames.find((f) => f.method === "$/cancel_request");
  assert.ok(request, "initialize was written");
  assert.ok(cancel, "$/cancel_request was written");
  assert.equal(cancel.params?.requestId, request.id);
});

