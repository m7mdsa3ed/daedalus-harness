test("the draft subagent_spawned is said as the RFD's announcement, whole and running", () => {
  const spawned = spawnToUpdate({
    sessionUpdate: "subagent_spawned",
    subagentSessionId: "kid",
    name: "Explore",
    task: "look",
    capabilities: { cancel: true },
    _meta: { daedalus: { parentToolUseId: "call_1" } },
  });
  assert.deepEqual(spawned, {
    sessionUpdate: "subagent_update",
    sessionId: "kid",
    title: "Explore",
    description: "look",
    capabilities: { cancel: {} },
    state: { state: "running" },
    _meta: { daedalus: { parentToolUseId: "call_1" } },
  });
  // No cancel: an empty capability set, which the RFD reads as "no mutations".
  const plain = spawnToUpdate({ sessionUpdate: "subagent_spawned", subagentSessionId: "kid", name: "n", task: "t", capabilities: {} });
  assert.deepEqual(plain.capabilities, {});
  assert.equal("cwd" in plain, false, "a placement the draft never said is not said as cleared");
  assert.equal("_meta" in plain, false);
  // The brief has no RFD field, so it rides `_meta.daedalus.prompt` — our runtime's own door.
  const briefed = spawnToUpdate({ sessionUpdate: "subagent_spawned", subagentSessionId: "kid", name: "n", task: "t", prompt: "the whole brief", capabilities: {}, _meta: { x: 1 } });
  assert.deepEqual(briefed._meta, { x: 1, daedalus: { prompt: "the whole brief" } });
  // One already there wins: the draft's `prompt` never overwrites it.
  const kept = spawnToUpdate({ sessionUpdate: "subagent_spawned", subagentSessionId: "kid", name: "n", task: "t", prompt: "late", capabilities: {}, _meta: { daedalus: { prompt: "first" } } });
  assert.deepEqual(kept._meta, { daedalus: { prompt: "first" } });
});

