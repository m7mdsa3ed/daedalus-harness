import { sql } from "drizzle-orm";
import { db } from "./db/index.js";

/*
 * Full-text search across thread transcripts.
 *
 * The index (`session_events_fts`, created at boot by `db/index.ts` — an
 * ordinary table carrying a generated `tsvector`, hidden from push) holds the
 * *user-and-agent-visible prose* of the journal, never the raw JSON: what the
 * user typed, what the agent answered and thought, and a tool call's title.
 * Tool rawInput/rawOutput stay out — a terminal dump or a diff would drown
 * every real match in noise and triple the index for text nobody searches by.
 *
 * Writes ride the same transaction cadence as the journal itself:
 * session-journal.ts calls `indexEventRow` from its buffered flush, so a
 * streaming turn costs one FTS insert per *prose* event inside the commit that
 * was happening anyway. Deletes are by session (`deleteSearchIndex`) from the
 * same three places the journal is cleared: a revive's `SessionJournal.clear`,
 * the retention sweep, and purge.
 */

/** Snippet markers — private-use codepoints that cannot appear in real prose,
    so the client can split on them without ever trusting markup. The client's
    copies live in client/src/lib/search.ts (protocol.ts must stay type-only
    importable, and these are runtime values). */
export const SNIPPET_START = "\u{E000}";
export const SNIPPET_END = "\u{E001}";

/** How many hits one thread may contribute — without a cap, one chatty thread
    that says the word fifty times is the entire first page. */
const PER_SESSION_CAP = 3;

export const SEARCH_LIMIT = 50;

interface EventRow {
  sessionId: string;
  seq: number;
  kind: string;
  payload: unknown;
  /** Optional to match the journal's insert type (the column defaults to 0);
      appendEvent always stamps it in practice. */
  at?: number;
}

/**
 * The searchable text of one journaled event, or null when it has none.
 *
 * `payload` is the journaled event object (`{ev, seq, ...}` — see protocol.ts).
 * Prose only: user/agent message chunks, thought chunks, the prompt a turn
 * started with, and a tool call's title. Everything else — tool inputs and
 * outputs, config, plans, terminal bytes — is deliberately not indexed.
 */
export function extractSearchText(kind: string, payload: unknown): string | null {
  if (payload === null || typeof payload !== "object") return null;
  const event = payload as Record<string, unknown>;
  if (kind === "turn_started") {
    return asText(event.text);
  }
  if (kind === "config_notice") {
    return asText(event.text);
  }
  if (kind !== "update") return null;
  const update = event.update as Record<string, unknown> | undefined;
  if (!update || typeof update !== "object") return null;
  switch (update.sessionUpdate) {
    case "user_message_chunk":
    case "agent_message_chunk":
    case "agent_thought_chunk": {
      const content = update.content as Record<string, unknown> | undefined;
      if (!content || typeof content !== "object" || content.type !== "text") return null;
      return asText(content.text);
    }
    // The title only ("Search the web for …"), never rawInput/rawOutput.
    case "tool_call":
      return asText(update.title);
    default:
      return null;
  }
}

const asText = (value: unknown): string | null => {
  if (typeof value !== "string") return null;
  const trimmed = value.trim();
  return trimmed.length > 0 ? trimmed : null;
};

/** The least a caller must be able to do — both `db` and a drizzle transaction
    qualify, which is what lets the journal flush index inside its own commit. */
interface SqlRunner {
  execute(query: ReturnType<typeof sql>): Promise<unknown>;
}

/** Index one journaled event. A no-op for events with no prose; returns
    whether a row was written. `tsv` is generated by the column, so prose is
    the only value there is to write. */
export async function indexEventRow(runner: SqlRunner, row: EventRow): Promise<boolean> {
  /* A workflow step's events are mirrored onto its parent's log carrying the
     step's `sessionId` (workflows.ts); they are indexed once, under the step's
     own thread, or every search hit in a step would come back twice. */
  if (row.kind === "update" && (row.payload as { sessionId?: unknown }).sessionId) return false;
  const text = extractSearchText(row.kind, row.payload);
  if (!text) return false;
  await runner.execute(
    sql`insert into session_events_fts (text, session_id, seq, at)
        values (${text}, ${row.sessionId}, ${row.seq}, ${row.at ?? 0})`,
  );
  return true;
}

/** Drop every indexed row of the given sessions — the mirror of the three
    places session_events rows are deleted. The table deliberately carries no
    foreign key back to `sessions`: the journal's flush is the hottest write
    this schema has, and a per-row FK check on it buys a cascade that these
    three callers already do.

    An `in (…)` list, not `= any($1)`: drizzle spreads a JS array into one
    parameter per element, so `any(${ids})` compiled to `any(($1))` and handed
    Postgres a bare id where it wanted an array literal — every call rejected
    with `malformed array literal`, and the one caller that matters
    (`SessionJournal.clear`, on every respawn) never reached the line that
    zeroes the session's seq counter. */
export async function deleteSearchIndex(sessionIds: string[]): Promise<void> {
  if (sessionIds.length === 0) return;
  const ids = sql.join(
    sessionIds.map((id) => sql`${id}`),
    sql`, `,
  );
  await db.execute(sql`delete from session_events_fts where session_id in (${ids})`);
}

/**
 * User input → a `tsquery` expression that cannot 500.
 *
 * `to_tsquery` gives `foo &`, `!`, `<->` and a lone `:*` syntax meaning (or a
 * syntax error), so nothing typed is handed to it as operators. Every
 * whitespace-separated term becomes a **single-quoted lexeme** with inner
 * quotes doubled, the terms are ANDed, and the final one gets `:*` so the word
 * still being typed matches as a prefix. Null when nothing is left.
 *
 * A term with no letter or digit in it is dropped rather than quoted: the
 * `simple` configuration lexes it to nothing, and an empty lexeme is the one
 * thing quoting does not make safe.
 */
export function ftsQuery(raw: string): string | null {
  const terms = raw
    .split(/\s+/)
    .filter((term) => /[\p{L}\p{N}]/u.test(term))
    .map((term) => term.replace(/'/g, "''"));
  if (terms.length === 0) return null;
  return terms.map((term, i) => (i === terms.length - 1 ? `'${term}':*` : `'${term}'`)).join(" & ");
}

export interface SearchResult {
  sessionId: string;
  seq: number;
  /** Prose with matches bracketed by SNIPPET_START/SNIPPET_END. */
  snippet: string;
  title: string;
  projectId: string;
  projectName: string;
  at: number;
  /** Turn containing the event, for jumping from a search hit into the transcript. */
  turnId: string | null;
  turnSeq: number | null;
}

/**
 * Search live (non-trashed) transcript prose, optionally scoped to one thread,
 * newest hits first. Each event is paired with its containing turn so a client
 * can jump into a windowed transcript. Title and project are resolved here —
 * the client's session list may not hold a thread whose journal still does.
 */
export async function searchEvents(
  raw: string,
  limit = SEARCH_LIMIT,
  sessionId?: string,
): Promise<SearchResult[]> {
  const match = ftsQuery(raw);
  if (!match) return [];
  const capped = Math.max(1, Math.min(limit, SEARCH_LIMIT));
  /* MaxFragments=1 rather than HighlightAll: the fragment is built around the
     match, which is what a result row wants. MinWords/MaxWords bracket the
     twelve tokens the FTS5 `snippet()` this replaced took as an argument, and
     ShortWord=0 keeps a one-letter identifier from being trimmed off the end
     of a fragment that is about it. */
  const headline =
    `StartSel=${SNIPPET_START}, StopSel=${SNIPPET_END}, MaxWords=12, MinWords=4, ` +
    `ShortWord=0, HighlightAll=FALSE, MaxFragments=1, FragmentDelimiter=…`;
  /* Aliases are quoted throughout: Postgres folds an unquoted identifier to
     lower case, so `as sessionId` would come back as `sessionid` and every
     reader below would be reading undefined. */
  const result = await db.execute<{
    sessionId: string;
    seq: number;
    snippet: string;
    at: number;
    turnId: string | null;
    turnSeq: number | null;
    title: string;
    projectId: string;
    projectName: string | null;
  }>(sql`
    with hits as (
      select f.session_id as "sessionId", f.seq as seq, f.at as at,
             ts_headline('simple', f.text, query, ${headline}) as snippet
      from session_events_fts f, to_tsquery('simple', ${match}) query
      where f.tsv @@ query
        and (${sessionId ?? null}::text is null or f.session_id = ${sessionId ?? null})
        and (
          ${sessionId ?? null}::text is null
          or exists (
            select 1 from session_events turn
            where turn.session_id = f.session_id
              and turn.kind = 'turn_started'
              and turn.seq <= f.seq
          )
        )
    ),
    located as (
      select hits.*,
             boundary.payload->>'turnId' as "turnId",
             boundary.seq as "turnSeq"
      from hits
      left join lateral (
        select e.seq, e.payload
        from session_events e
        where e.session_id = hits."sessionId"
          and e.kind = 'turn_started'
          and e.seq <= hits.seq
        order by e.seq desc
        limit 1
      ) boundary on true
    ),
    ranked as (
      select located.*,
             row_number() over (partition by "sessionId" order by at desc, seq desc) as rn
      from located
    )
    select f."sessionId" as "sessionId", f.seq as "seq", f.snippet as "snippet", f.at as "at",
           f."turnId" as "turnId", f."turnSeq" as "turnSeq",
           s.title as "title", s.project_id as "projectId", p.name as "projectName"
    from ranked f
    join sessions s on s.id = f."sessionId" and s.deleted_at is null
    left join projects p on p.id = s.project_id
    where f.rn <= ${PER_SESSION_CAP}
    order by f.at desc, f.seq desc
    limit ${capped}
  `);
  return result.rows.map((row) => ({ ...row, projectName: row.projectName ?? "" }));
}

/**
 * Index everything journaled before the index existed. Runs at boot, before
 * the server listens (so nothing streams while it walks), and once: progress
 * is a cursor in `search_meta`, advanced per page inside each page's
 * transaction, with a terminal "done" marker — so a crash mid-backfill resumes
 * where it stopped instead of double-indexing, and a finished install pays one
 * SELECT per boot.
 *
 * The cursor is the primary key `(session_id, seq)` rather than a rowid:
 * Postgres has no rowid, and the pair is the ordering `session_events` is
 * already stored and indexed by. Compared as a row constructor, so the paging
 * predicate is the one an index can answer.
 */
export async function backfillSearchIndex(): Promise<void> {
  const state = await db.execute<{ value: string }>(
    sql`select value from search_meta where key = 'fts_backfill'`,
  );
  const stored = state.rows[0]?.value;
  if (stored === "done") return;
  let cursor: { sessionId: string; seq: number } = { sessionId: "", seq: -1 };
  if (stored) {
    try {
      const parsed = JSON.parse(stored) as { sessionId?: unknown; seq?: unknown };
      if (typeof parsed.sessionId === "string" && typeof parsed.seq === "number") {
        cursor = { sessionId: parsed.sessionId, seq: parsed.seq };
      }
    } catch {
      /* A cursor left by the SQLite build was a rowid, which means nothing
         here; start from the beginning rather than from a number that happens
         to parse. Re-indexing is idempotent only up to duplicates, and the
         table this walks is empty on a fresh Postgres install anyway. */
    }
  }
  const PAGE = 2000;
  let indexed = 0;
  for (;;) {
    const page = await db.execute<{
      sessionId: string;
      seq: number;
      kind: string;
      payload: string;
      at: number;
    }>(sql`
      select session_id as "sessionId", seq as "seq", kind as "kind",
             payload::text as "payload", at as "at"
      from session_events
      where (session_id, seq) > (${cursor.sessionId}, ${cursor.seq})
      order by session_id, seq
      limit ${PAGE}
    `);
    const rows = page.rows;
    if (rows.length === 0) break;
    cursor = { sessionId: rows[rows.length - 1].sessionId, seq: rows[rows.length - 1].seq };
    const mark = JSON.stringify(cursor);
    await db.transaction(async (tx) => {
      for (const row of rows) {
        let payload: unknown;
        try {
          payload = JSON.parse(row.payload);
        } catch {
          continue; // an unreadable payload has no searchable prose
        }
        if (await indexEventRow(tx, { ...row, payload })) indexed += 1;
      }
      await tx.execute(sql`
        insert into search_meta (key, value) values ('fts_backfill', ${mark})
        on conflict (key) do update set value = excluded.value
      `);
    });
    if (rows.length < PAGE) break;
  }
  await db.execute(sql`
    insert into search_meta (key, value) values ('fts_backfill', 'done')
    on conflict (key) do update set value = 'done'
  `);
  if (indexed > 0) console.log(`[search] backfilled ${indexed} journaled event(s) into the index`);
}
