/*
 * The `harness` MCP server's tool catalog.
 *
 * One entry per tool, and one tool per `/api` route the client itself calls —
 * the harness MCP is a named, authenticated proxy to the harness's own REST
 * surface, so "everything the client can do" is this table and nothing else.
 *
 * This module is pure (zod and nothing else): the stdio child imports it to
 * register the tools, and `routes/harness.ts` is a single generic proxy, so
 * neither side spells a route twice. Adding a capability is one entry here plus
 * the route it names, and the route already exists because the browser uses it.
 *
 * Deliberately absent: the streaming reads (spans/watch; replay is offered only as the windowed `threads_read`), the file,
 * terminal and git workspace routes, attachments and the OAuth callbacks — an
 * agent has its own filesystem and shell, those responses are unbounded or
 * browser-interactive, and none of them is "managing the harness".
 */
import { z } from "zod";

export type HarnessMethod = "GET" | "POST" | "PUT" | "PATCH" | "DELETE";

export interface HarnessTool {
  /** `group_verb` — the tool the model sees (`mcp__harness__profiles_create`). */
  name: string;
  title: string;
  description: string;
  method: HarnessMethod;
  /** A route path. `:name` segments are filled from `params`. */
  path: string;
  /** Path parameters; also what the child substitutes into `path`. */
  params?: z.ZodRawShape;
  /** Query-string parameters. */
  query?: z.ZodRawShape;
  /** The tool takes free-form body fields, passed as one `data` object and
      validated by the route's own schema — what the client's form posts. */
  data?: true;
  readOnly?: boolean;
  destructive?: boolean;
  idempotent?: boolean;
}

